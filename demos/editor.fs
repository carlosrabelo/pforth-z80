8 CONSTANT NUM-BLOCKS
VARIABLE BLOCKS 8192 ALLOT

VARIABLE CURRENT-BLOCK
0 CURRENT-BLOCK !

: FILL
  ROT ROT 0 DO
    OVER OVER I + C!
  LOOP DROP DROP ;

: BLOCK
  1024 * BLOCKS + ;

: CLEAR
  BLOCK 1024 32 FILL ;

: INIT-BLOCKS
  BLOCKS 8192 32 FILL ;

: WIPE
  CURRENT-BLOCK @ CLEAR ;

: .LINE
  DUP .
  64 * CURRENT-BLOCK @ BLOCK +
  64 TYPE CR ;

: .DASHES
  45 EMIT 45 EMIT 45 EMIT ;

: .HEADER
  CR .DASHES 32 EMIT
  66 EMIT 76 EMIT 79 EMIT 67 EMIT 75 EMIT 32 EMIT
  DUP .
  .DASHES CR ;

: LIST
  DUP CURRENT-BLOCK !
  DUP .HEADER
  16 0 DO
    I .LINE
  LOOP ;

: PUT
  64 * CURRENT-BLOCK @ BLOCK +
  DUP 64 32 FILL
  64 EXPECT ;
